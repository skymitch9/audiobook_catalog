"""Audible product data for files whose own tags carry Audible's placeholders.

WHY THIS EXISTS (2026-11-24)
----------------------------
``app/tools/audible_download.py`` used to remux Audible's AAX/AAXC with
``ffmpeg -c copy`` and nothing else, so the m4b kept Audible's raw CONTAINER
tags: ``©gen = "Audiobook"`` (a placeholder, never a real category),
``©day = "2000"`` on some titles, a title ending in "(Unabridged)", and no
``CDEK`` (ASIN), ``SRNM`` or ``SRSQ`` at all. 132 library files came out that
way. The converter now writes proper tags into each NEW file it creates; this
module covers the files that already exist, WITHOUT writing to them —
purchased media is never retagged for a title/date/genre correction
(``docs/info/catalog-corrections.md``).

THE DATA
--------
``scripts/audible_backfill.json`` is GENERATED by
``python -m app.tools.build_audible_backfill`` from a read-only
``audible-cli library export``. Each entry names one library file by the raw
tags it carries (``©nam`` + ``©ART``, or its ``CDEK`` when it has one) and
gives Audible's own ``genre`` (one category ladder, ``Top:Sub:Leaf``, the
same shape OpenAudible writes) and ``release_date``, keyed by ASIN.

Only PUBLIC product fields are stored — this repo is public. No purchase
dates, no account/profile names, no titles the library does not hold.

WHAT IT MAY CHANGE
------------------
Fill-only, and only over a placeholder:

* ``genre`` when the tag says ``Audiobook`` (or nothing);
* ``year`` when the tag year is a known placeholder (``2000``, or a year in
  the future such as Audible's ``2200``) AND Audible gives a real one.

It never overrides a real tag value, and the corrections layer
(``scripts/catalog_overrides.json``) still runs after it and wins.

A missing or malformed file is a NO-OP, exactly like the corrections layer.
"""

from __future__ import annotations

import datetime as _dt
import json
import re
from pathlib import Path
from typing import Any, Dict, Optional

BACKFILL_PATH = Path(__file__).resolve().parent.parent.parent / "scripts" / "audible_backfill.json"

# Values Audible's container tags use when they have nothing real to say.
PLACEHOLDER_GENRES = {"", "audiobook"}
PLACEHOLDER_YEARS = {"2000"}

_YEAR = re.compile(r"^\s*(\d{4})")


def _year_of(value: Optional[str]) -> Optional[int]:
    m = _YEAR.match(value or "")
    return int(m.group(1)) if m else None


def is_placeholder_year(value: Optional[str], today: Optional[_dt.date] = None) -> bool:
    """'2000' (Audible's container default) or any year after next year.

    ⚠️ Only a BARE year can be '2000': a full date like '2000-03-14' is a
    real date somebody wrote, and is left alone."""
    v = (value or "").strip()
    if v in PLACEHOLDER_YEARS:
        return True
    y = _year_of(v)
    this_year = (today or _dt.date.today()).year
    return y is not None and y > this_year + 1


def is_placeholder_genre(value: Optional[str]) -> bool:
    return (value or "").strip().lower() in PLACEHOLDER_GENRES


def _norm(s: Optional[str]) -> str:
    return re.sub(r"\s+", " ", str(s or "")).strip()


def _load(path: Path = BACKFILL_PATH) -> Dict[str, Any]:
    empty = {"by_asin": {}, "by_tags": {}, "genre_paths": []}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return empty
    if not isinstance(data, dict):
        return empty
    by_asin: Dict[str, dict] = {}
    by_tags: Dict[tuple, dict] = {}
    for e in data.get("entries") or []:
        if not isinstance(e, dict) or not e.get("asin"):
            continue
        m = e.get("match") or {}
        if m.get("asin"):
            by_asin[_norm(m["asin"]).upper()] = e
        elif m.get("title_tag"):
            by_tags[(_norm(m["title_tag"]), _norm(m.get("artist_tag")))] = e
    return {"by_asin": by_asin, "by_tags": by_tags, "genre_paths": list(data.get("genre_paths") or [])}


_DATA = _load()


def reload(path: Path = BACKFILL_PATH) -> None:
    """Re-read the file (tests point this at a temp file)."""
    global _DATA
    _DATA = _load(path)


def genre_paths() -> list:
    return list(_DATA["genre_paths"])


def lookup(title_tag: Optional[str], artist_tag: Optional[str], asin_tag: Optional[str]) -> Optional[dict]:
    """The entry for one file, by its CDEK if it has one, else by its RAW
    ``©nam`` + ``©ART`` exactly as they sit in the file (pre-derivation, so a
    change to the title or casing rules can never silently unkey an entry)."""
    if asin_tag:
        hit = _DATA["by_asin"].get(_norm(asin_tag).upper())
        if hit is not None:
            return hit
    if title_tag:
        return _DATA["by_tags"].get((_norm(title_tag), _norm(artist_tag)))
    return None


def fill(row: Dict[str, Optional[str]], entry: Optional[dict]) -> Dict[str, Optional[str]]:
    """Return a copy of ``row`` with placeholder genre/year replaced from
    ``entry``. A future year with no Audible replacement is BLANKED: no book
    was released in 2200, and an empty year is honest where a fake one is not."""
    out = dict(row)
    if entry:
        g = _norm(entry.get("genre"))
        if g and is_placeholder_genre(out.get("genre")):
            out["genre"] = g
        rd = _norm(entry.get("release_date"))
        if rd and not is_placeholder_year(rd) and is_placeholder_year(out.get("year")):
            out["year"] = rd
    y = _year_of(out.get("year"))
    if y is not None and is_placeholder_year(out.get("year")) and (out.get("year") or "").strip() not in PLACEHOLDER_YEARS:
        out["year"] = ""
    return out


# ---------------------------------------------------------------------------
# Genre ladders — shared by the backfill builder and the converter.
# ---------------------------------------------------------------------------
def split_ladders(flat: str, known_paths: list) -> list:
    """audible-cli flattens Audible's ``category_ladders`` into ONE comma list
    ("Literature & Fiction, Classics, Science Fiction & Fantasy, Fantasy, ...")
    — and some category names contain commas themselves ("Mystery, Thriller &
    Suspense"). This rebuilds the ladders using the set of ladder paths the
    library's own OpenAudible tags already contain (``known_paths``, each a
    ``Top:Sub:Leaf`` string).

    Measured 2026-11-24 on the 913 files that carry both an OpenAudible genre
    and an export row: the FIRST rebuilt ladder equals OpenAudible's own pick
    730 times, the OpenAudible pick is among the rebuilt ladders 857 times,
    and the first ladder is a real library path 912 times. So it always yields
    a genuine Audible category for the book, but not always the one OpenAudible
    chose."""
    paths = {tuple(p.split(":")) for p in known_paths}
    prefixes = {pp[:k] for pp in paths for k in range(1, len(pp) + 1)}
    roots = {pp[0] for pp in paths}
    names = {seg for pp in paths for seg in pp}
    parts = [x.strip() for x in (flat or "").split(",") if x.strip()]
    tokens, i = [], 0
    while i < len(parts):
        for j in range(len(parts), i, -1):
            cand = ", ".join(parts[i:j])
            if j - i == 1 or cand in names:
                tokens.append(cand)
                i = j
                break
    ladders, cur = [], []
    for t in tokens:
        if cur and tuple(cur + [t]) in prefixes:
            cur.append(t)
        elif cur and t not in roots and tuple(cur) not in prefixes:
            cur.append(t)
        else:
            if cur:
                ladders.append(cur)
            cur = [t]
    if cur:
        ladders.append(cur)
    return [":".join(c) for c in ladders]


def first_known_ladder(flat: str, known_paths: list) -> str:
    """The first rebuilt ladder that is a real library path (or a leading
    part of one), else ''. An unknown ladder is refused rather than guessed."""
    known = {":".join(p.split(":")[:k]) for p in known_paths for k in range(1, len(p.split(":")) + 1)}
    for lad in split_ladders(flat, known_paths):
        if lad in known:
            return lad
    return ""
